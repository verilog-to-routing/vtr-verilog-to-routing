// exotic hardblock generators: stub-all, -exotic templates, and -exotic-role maps.

// HELPER: make a token-safe port name (uppercase, non-alnum becomes '_').
std::string tokenName(const std::string &port) {
    std::string out;
    for (char c : port)
        out += isalnum((unsigned char)c) ? (char)toupper((unsigned char)c) : '_';
    return out;
}

// HELPER: generic blackbox stub from scanned port geometry when the exotic
// template carries no stub of its own. ports emit in sorted name order with
// inputs before outputs. 1-bit ports get no range.
std::string genericStub(const std::string &model, const ModelGeometry &geo) {
    std::ostringstream ports;
    bool first = true;
    auto port = [&](const char *dir, const std::string &name, int width) {
        if (!first)
            ports << ",\n";
        first = false;
        ports << "    " << dir << " ";
        if (width > 1)
            ports << "[" << (width - 1) << ":0] ";
        ports << name;
    };
    for (const auto &kv : geo.inputWidths)
        port("input", kv.first, kv.second);
    for (const auto &kv : geo.outputWidths)
        port("output", kv.first, kv.second);

    std::ostringstream out;
    out << "(* blackbox *)\n";
    out << "module " << model << " (\n";
    out << ports.str() << "\n";
    out << ");\n";
    out << "endmodule\n";
    return finishStub(out.str());
}

// HELPER: identity techmap where a Yosys cell with the exotic model name maps
// to the same hardblock with 1:1 port connections.
std::string identityTechmapModule(const std::string &model, const ModelGeometry &geo) {
    std::ostringstream decl;
    std::ostringstream conn;
    bool firstDecl = true;
    bool firstConn = true;
    auto port = [&](const char *dir, const std::string &name, int width) {
        if (!firstDecl)
            decl << ",\n";
        firstDecl = false;
        decl << "    " << dir << " ";
        if (width > 1)
            decl << "[" << (width - 1) << ":0] ";
        decl << name;

        if (!firstConn)
            conn << ",\n";
        firstConn = false;
        conn << "        ." << name << "(" << name << ")";
    };
    for (const auto &kv : geo.inputWidths)
        port("input", kv.first, kv.second);
    for (const auto &kv : geo.outputWidths)
        port("output", kv.first, kv.second);

    std::ostringstream out;
    out << "// this identity techmap binds " << model << " to itself.\n";
    out << "module " << model << " (\n";
    out << decl.str() << "\n";
    out << ");\n\n";
    out << "    " << model << " _TECHMAP_REPLACE_ (\n";
    out << conn.str() << "\n";
    out << "    );\n";
    out << "endmodule\n\n";
    return out.str();
}

// HELPER: detect a/b/out port geometry required for integer_mul style roles.
bool hasAbOutPorts(const ModelGeometry &geo) {
    return geo.inputWidths.count("a") && geo.inputWidths.count("b") && geo.outputWidths.count("out");
}

// HELPER: derive multiply mode widths from scanned geometry for exotic roles.
std::vector<int> exoticMulModes(const ModelGeometry &geo) {
    if (!geo.modes.empty())
        return geo.modes;
    auto a = geo.inputWidths.find("a");
    if (a != geo.inputWidths.end() && a->second > 0)
        return {a->second};
    return {};
}

// HELPER: built-in always-fail map for a missing exotic model.
std::string alwaysFailExoticMap(const std::string &archName, const std::string &model) {
    std::ostringstream out;
    out << "// " << model << "_map.v. generated by vtr_arch_rules from " << archName << "\n";
    out << "// the arch has no \"" << model
        << "\" hardblock model, so this map "
           "always fails and matching cells stay soft.\n";
    out << "module \\" << model << " (A, B, Y);\n";
    out << "    parameter WIDTH = 1;\n";
    out << "    input  [WIDTH-1:0] A;\n";
    out << "    input  [WIDTH-1:0] B;\n";
    out << "    output [WIDTH-1:0] Y;\n";
    out << "    wire _TECHMAP_FAIL_ = 1'b1;\n";
    out << "endmodule\n";
    return out.str();
}

// stub generator for every non-builtin hardblock model.
class StubAllExoticsRuleGen : public ArchRuleGen {
  public:
    StubAllExoticsRuleGen() : ArchRuleGen("stub-all-exotics") {}

    // USE: write hardblock_keep_types.txt and identity passthrough maps for exotics.
    void emit(const VtrArchInfo &info, const ArchRulePolicy &policy, const std::string &outDir) const override {
        std::ostringstream keep;
        std::ostringstream identityMaps;
        bool first = true;
        for (const auto &kv : info.hardblockModels) {
            if (isBuiltinHardblock(kv.first, policy.classic))
                continue;
            if (!first)
                keep << " ";
            first = false;
            keep << "t:" << kv.first;
            identityMaps << identityTechmapModule(kv.first, kv.second);
        }
        keep << "\n";
        writeFile(outDir + "/hardblock_keep_types.txt", keep.str());
        if (!identityMaps.str().empty()) {
            std::ostringstream header;
            header << "// exotic_identity_maps.v. generated by vtr_arch_rules from " << policy.archName << "\n";
            header << "// these maps pass scanned exotic hardblocks through by cell name.\n\n";
            writeFile(outDir + "/exotic_identity_maps.v", header.str() + identityMaps.str());
        }
    }

    // USE: contribute generic blackbox stubs for every non-builtin hardblock.
    std::string hardblockStub(const VtrArchInfo &info, const ArchRulePolicy &policy) const override {
        std::ostringstream stubs;
        for (const auto &kv : info.hardblockModels) {
            if (isBuiltinHardblock(kv.first, policy.classic))
                continue;
            stubs << genericStub(kv.first, kv.second);
        }
        return stubs.str();
    }
};

// combinational-kind generator for generic -exotic extension requests.
class ExoticCombRuleGen : public ArchRuleGen {
  public:
    explicit ExoticCombRuleGen(ExoticRequest request) : ArchRuleGen(request.modelName), request_(std::move(request)) {}

    // USE: emit a per-model techmap from the user-supplied exotic template.
    void emit(const VtrArchInfo &info, const ArchRulePolicy &policy, const std::string &outDir) const override {
        auto it = info.hardblockModels.find(request_.modelName);
        if (it == info.hardblockModels.end()) {
            log_warning("vtr_arch_rules: exotic model '%s' not in arch; emitting "
                        "always-fail map\n",
                        request_.modelName.c_str());
            writeFile(outDir + "/" + request_.modelName + "_map.v",
                      alwaysFailExoticMap(policy.archName, request_.modelName));
            return;
        }
        const ModelGeometry &geo = it->second;

        std::string text = readTextFile(request_.templatePath);
        // optional first-line directive "// output-name: <file>" or "# ..." selects
        // the emitted file name, and the default is <model>_map.v.
        std::string outName = request_.modelName + "_map.v";
        const size_t eol = text.find('\n');
        const std::string firstLine = eol == std::string::npos ? text : text.substr(0, eol);
        const std::string directive = "output-name:";
        size_t dpos = firstLine.find(directive);
        if ((firstLine.rfind("//", 0) == 0 || firstLine.rfind("#", 0) == 0) && dpos != std::string::npos) {
            outName = firstLine.substr(dpos + directive.size());
            while (!outName.empty() && isspace((unsigned char)outName.front()))
                outName.erase(outName.begin());
            while (!outName.empty() && isspace((unsigned char)outName.back()))
                outName.pop_back();
            text.erase(0, eol == std::string::npos ? eol : eol + 1);
        }

        std::map<std::string, std::string> scalars = {
            {"ARCH_NAME", policy.archName},
            {"MODEL_NAME", request_.modelName},
            {"MAX_A_WIDTH", std::to_string(geo.modes.empty() ? 0 : geo.modes.back())},
            {"MODES", geo.modes.empty() ? "-" : joinInts(geo.modes, ",")},
        };
        for (const auto &kv : geo.inputWidths)
            scalars["PORT_IN_" + tokenName(kv.first)] = std::to_string(kv.second);
        for (const auto &kv : geo.outputWidths)
            scalars["PORT_OUT_" + tokenName(kv.first)] = std::to_string(kv.second);

        writeFile(outDir + "/" + outName, substituteTemplate(text, scalars, {}));
    }

    // USE: contribute a generic stub when the exotic template has no stub section.
    std::string hardblockStub(const VtrArchInfo &info, const ArchRulePolicy &) const override {
        auto it = info.hardblockModels.find(request_.modelName);
        if (it == info.hardblockModels.end())
            return {};
        return genericStub(request_.modelName, it->second);
    }

  private:
    ExoticRequest request_;
};

// combinational-kind generator using stock role templates under tpldir/roles/.
class RoleRuleGen : public ArchRuleGen {
  public:
    RoleRuleGen(ExoticRoleRequest request, std::string *emittedMapPath)
        : ArchRuleGen("role:" + request.modelName + ":" + request.roleName), request_(std::move(request)),
          emittedMapPath_(emittedMapPath) {}

    // USE: emit a role-based techmap from roles/<role>_map.v.tmpl.
    void emit(const VtrArchInfo &info, const ArchRulePolicy &policy, const std::string &outDir) const override {
        if (emittedMapPath_)
            emittedMapPath_->clear();

        if (request_.roleName == "integer_mul" && info.multiply.present && !info.multiplyModes.empty()) {
            log("vtr_arch_rules: skipping integer_mul role for '%s' because classic "
                "multiply model '%s' is present\n",
                request_.modelName.c_str(), policy.classic.multiply.c_str());
            return;
        }

        auto it = info.hardblockModels.find(request_.modelName);
        if (it == info.hardblockModels.end()) {
            log_warning("vtr_arch_rules: exotic role model '%s' not in arch; "
                        "emitting always-fail map\n",
                        request_.modelName.c_str());
            const std::string outPath = outDir + "/" + request_.modelName + "_map.v";
            writeFile(outPath, alwaysFailExoticMap(policy.archName, request_.modelName));
            if (emittedMapPath_)
                *emittedMapPath_ = outPath;
            return;
        }
        const ModelGeometry &geo = it->second;

        if ((request_.roleName == "integer_mul" || request_.roleName == "integer_mac") && !hasAbOutPorts(geo)) {
            log_warning("vtr_arch_rules: model '%s' lacks a/b/out ports required for role "
                        "'%s'; emitting always-fail map\n",
                        request_.modelName.c_str(), request_.roleName.c_str());
            const std::string outPath = outDir + "/" + request_.modelName + "_map.v";
            writeFile(outPath, alwaysFailExoticMap(policy.archName, request_.modelName));
            if (emittedMapPath_)
                *emittedMapPath_ = outPath;
            return;
        }

        if (policy.tplDir.empty())
            log_cmd_error("vtr_arch_rules: -tpldir <dir> is required for role '%s'\n", request_.roleName.c_str());
        std::string text = loadTemplate(policy, "roles/" + request_.roleName + "_map.v.tmpl");

        const std::vector<int> mulModes = exoticMulModes(geo);
        const int maxW = mulModes.empty() ? 0 : mulModes.back();
        std::map<std::string, std::string> scalars = {
            {"ARCH_NAME", policy.archName},
            {"MODEL_NAME", request_.modelName},
            {"MAX_A_WIDTH", std::to_string(maxW)},
            {"MULT_MAX_WIDTH", std::to_string(maxW)},
            {"MULT_MIN_WIDTH", std::to_string(std::max(0, policy.minHardMulWidth))},
            {"MODES", mulModes.empty() ? "-" : joinInts(mulModes, ",")},
            {"HAS_ACC_PORT", geo.inputWidths.count("acc") ? "1" : "0"},
        };
        for (const auto &kv : geo.inputWidths)
            scalars["PORT_IN_" + tokenName(kv.first)] = std::to_string(kv.second);
        for (const auto &kv : geo.outputWidths)
            scalars["PORT_OUT_" + tokenName(kv.first)] = std::to_string(kv.second);

        std::map<std::string, std::string> snippets;
        if (!mulModes.empty()) {
            snippets["MULT_TERNARY"] = multTernary(mulModes);
            snippets["MULT_NEED_TERNARY"] = multTernarySingle("needW", mulModes);
        } else {
            snippets["MULT_TERNARY"] = "0";
            snippets["MULT_NEED_TERNARY"] = "0";
        }

        const std::string outPath = outDir + "/" + request_.modelName + "_map.v";
        writeFile(outPath, substituteTemplate(text, scalars, snippets));
        if (emittedMapPath_)
            *emittedMapPath_ = outPath;
    }

    // USE: contribute a generic stub for the role-bound exotic model.
    std::string hardblockStub(const VtrArchInfo &info, const ArchRulePolicy &) const override {
        auto it = info.hardblockModels.find(request_.modelName);
        if (it == info.hardblockModels.end())
            return {};
        return genericStub(request_.modelName, it->second);
    }

  private:
    ExoticRoleRequest request_;
    std::string *emittedMapPath_;
};

std::unique_ptr<ArchRuleGen> makeExoticRuleGenImpl(const ExoticRequest &request) {
    return std::unique_ptr<ArchRuleGen>(new ExoticCombRuleGen(request));
}

std::unique_ptr<ArchRuleGen> makeRoleRuleGenImpl(const ExoticRoleRequest &request, std::string *emittedMapPath) {
    return std::unique_ptr<ArchRuleGen>(new RoleRuleGen(request, emittedMapPath));
}

std::unique_ptr<ArchRuleGen> makeStubAllExoticsGenImpl() {
    return std::unique_ptr<ArchRuleGen>(new StubAllExoticsRuleGen());
}

