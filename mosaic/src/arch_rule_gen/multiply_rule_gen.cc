// combinational-kind generator: mult_map.v, mul2dsp_map.v, and multiply stub.

// HELPER: MULT_W mode-selection ternary picking the smallest mode that fits
// both extended operands, with the widest mode as fallthrough.
std::string multTernary(const std::vector<int> &modes) {
    std::ostringstream out;
    for (size_t i = 0; i + 1 < modes.size(); ++i)
        out << "(AW <= " << modes[i] << " && BW <= " << modes[i] << ") ? " << modes[i] << " : ";
    out << modes.back();
    return out.str();
}

// HELPER: same ternary over one combined width expression for mul2dsp needW.
std::string multTernarySingle(const char *widthExpr, const std::vector<int> &modes) {
    std::ostringstream out;
    for (size_t i = 0; i + 1 < modes.size(); ++i)
        out << "(" << widthExpr << " <= " << modes[i] << ") ? " << modes[i] << " : ";
    out << modes.back();
    return out.str();
}

// HELPER: builtins already receive stubs or whiteboxes from other generators.
bool isBuiltinHardblock(const std::string &name, const ClassicModelNames &classic) {
    return name == classic.multiply || name == classic.adder || name == classic.singlePortRam ||
           name == classic.dualPortRam;
}

// HELPER: max data width across all scanned bram modes for ram stub sizing.
int maxBramDataWidth(const VtrArchInfo &info) {
    int maxWidth = 1;
    for (const auto &mode : info.bramModes)
        maxWidth = std::max(maxWidth, std::max(mode.dataBitsA, mode.dataBitsB));
    return maxWidth;
}

// HELPER: detect whether the arch carries any non-builtin exotic hardblocks.
bool hasExoticHardblocks(const VtrArchInfo &info, const ClassicModelNames &classic) {
    for (const auto &kv : info.hardblockModels)
        if (!isBuiltinHardblock(kv.first, classic))
            return true;
    return false;
}

// HELPER: warn when inferred $mul cannot map because only exotic multiply exists.
void warnExoticOnlyMultiply(const VtrArchInfo &info, const ClassicModelNames &classic) {
    if (info.multiply.present || !hasExoticHardblocks(info, classic))
        return;
    log_warning("vtr_arch_rules: arch has exotic hardblock models but no classic "
                "'%s' model; inferred $mul will not map to exotics. use "
                "stubAllHardblocks for rtl-instantiated exotic cells, "
                "exoticRoles / -exotic-role for role inference, or "
                "exoticTemplatePairs / -exotic for a per-model techmap.\n",
                classic.multiply.c_str());
}

// HELPER: built-in always-fail map for archs without a multiply model.
std::string alwaysFailMultMap(const std::string &archName) {
    std::ostringstream out;
    out << "// mult_map.v. generated by vtr_arch_rules from " << archName << "\n";
    out << "// the arch has no multiply model, so this map always fails and $mul stays soft.\n";
    out << "module \\$mul (A, B, Y);\n";
    out << "    parameter A_SIGNED = 0;\n";
    out << "    parameter B_SIGNED = 0;\n";
    out << "    parameter A_WIDTH  = 1;\n";
    out << "    parameter B_WIDTH  = 1;\n";
    out << "    parameter Y_WIDTH  = 1;\n\n";
    out << "    input  [A_WIDTH-1:0] A;\n";
    out << "    input  [B_WIDTH-1:0] B;\n";
    out << "    output [Y_WIDTH-1:0] Y;\n\n";
    out << "    wire _TECHMAP_FAIL_ = 1'b1;\n";
    out << "endmodule\n";
    return out.str();
}

// HELPER: built-in always-fail map for mul2dsp when no multiply model exists.
// dspMaxWidth should be 0 there so mul2dsp never builds a _dsp_block_.
std::string alwaysFailMul2dspMap(const std::string &archName) {
    std::ostringstream out;
    out << "// mul2dsp_map.v. generated by vtr_arch_rules from " << archName << "\n";
    out << "// the arch has no multiply model, so this map always fails and "
           "_dsp_block_ chunks never bind to a hardblock.\n";
    out << "module _dsp_block_ (A, B, Y);\n";
    out << "    parameter A_SIGNED = 0;\n";
    out << "    parameter B_SIGNED = 0;\n";
    out << "    parameter A_WIDTH  = 1;\n";
    out << "    parameter B_WIDTH  = 1;\n";
    out << "    parameter Y_WIDTH  = 1;\n\n";
    out << "    input  [A_WIDTH-1:0] A;\n";
    out << "    input  [B_WIDTH-1:0] B;\n";
    out << "    output [Y_WIDTH-1:0] Y;\n\n";
    out << "    wire _TECHMAP_FAIL_ = 1'b1;\n";
    out << "endmodule\n";
    return out.str();
}

// combinational-kind generator: mult_map.v and multiply lib stub.
class MultiplyRuleGen : public ArchRuleGen {
  public:
    MultiplyRuleGen() : ArchRuleGen("multiply") {}

    // USE: emit mult_map.v and mul2dsp_map.v from scanned multiply modes.
    void emit(const VtrArchInfo &info, const ArchRulePolicy &policy, const std::string &outDir) const override {
        if (!info.multiply.present || info.multiplyModes.empty()) {
            warnExoticOnlyMultiply(info, policy.classic);
            log_warning("vtr_arch_rules: no multiply model in arch; emitting "
                        "always-fail mult_map.v and mul2dsp_map.v\n");
            writeFile(outDir + "/mult_map.v", alwaysFailMultMap(policy.archName));
            writeFile(outDir + "/mul2dsp_map.v", alwaysFailMul2dspMap(policy.archName));
            return;
        }
        const int maxW = info.multiplyModes.back();
        const int minHardW = std::max(0, policy.minHardMulWidth);
        if (minHardW > 0) {
            log("vtr_arch_rules: minHardMulWidth=%d ($mul stays soft when both "
                "operand widths <= threshold)\n",
                minHardW);
        }
        const std::map<std::string, std::string> scalars = {
            {"ARCH_NAME", policy.archName},
            {"MULT_MAX_WIDTH", std::to_string(maxW)},
            {"MULT_MIN_WIDTH", std::to_string(minHardW)},
            {"MULT_MODEL", policy.classic.multiply},
        };
        const std::map<std::string, std::string> snippets = {
            {"MULT_TERNARY", multTernary(info.multiplyModes)},
        };
        writeFile(outDir + "/mult_map.v",
                  substituteTemplate(loadTemplate(policy, "mult_map.v.tmpl"), scalars, snippets));
        writeFile(outDir + "/mul2dsp_map.v",
                  substituteTemplate(loadTemplate(policy, "mul2dsp_map.v.tmpl"), scalars,
                                     {{"MULT_NEED_TERNARY", multTernarySingle("needW", info.multiplyModes)}}));
    }

    // USE: contribute multiply blackbox stub sized from widest scanned mode.
    std::string hardblockStub(const VtrArchInfo &info, const ArchRulePolicy &policy) const override {
        if (!info.multiply.present || info.multiplyModes.empty())
            return {};
        const int maxW = info.multiplyModes.back();
        const std::map<std::string, std::string> scalars = {
            {"MULT_MAX_WIDTH", std::to_string(maxW)},
            {"MULT_PRODUCT_WIDTH", std::to_string(2 * maxW)},
            {"MULT_MODEL", policy.classic.multiply},
        };
        return finishStub(substituteTemplate(loadTemplate(policy, "multiply_stub.v.tmpl"), scalars, {}));
    }
};

std::unique_ptr<ArchRuleGen> makeMultiplyRuleGen() { return std::unique_ptr<ArchRuleGen>(new MultiplyRuleGen()); }

