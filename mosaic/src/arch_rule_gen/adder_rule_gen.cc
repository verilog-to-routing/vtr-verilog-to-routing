// combinational-kind generator: add_sub_map.v and adder lib stub.

// HELPER: built-in always-fail map when hard $add/$sub binding is unavailable.
std::string alwaysFailAddSubMap(const std::string &archName, const char *reasonLine) {
    std::ostringstream out;
    out << "// add_sub_map.v. generated by vtr_arch_rules from " << archName << "\n";
    out << "// " << reasonLine << "\n";
    out << "// this map always fails so $add/$sub stay soft.\n";
    for (const char *op : {"$add", "$sub"}) {
        out << "module \\" << op << " (A, B, Y);\n";
        out << "    parameter A_SIGNED = 0;\n";
        out << "    parameter B_SIGNED = 0;\n";
        out << "    parameter A_WIDTH  = 1;\n";
        out << "    parameter B_WIDTH  = 1;\n";
        out << "    parameter Y_WIDTH  = 1;\n\n";
        out << "    input  [A_WIDTH-1:0] A;\n";
        out << "    input  [B_WIDTH-1:0] B;\n";
        out << "    output [Y_WIDTH-1:0] Y;\n\n";
        out << "    wire _TECHMAP_FAIL_ = 1'b1;\n";
        out << "endmodule\n";
    }
    return out.str();
}

// combinational-kind generator: add_sub_map.v and adder lib stub.
class AdderRuleGen : public ArchRuleGen {
  public:
    AdderRuleGen() : ArchRuleGen("adder") {}

    // USE: emit add_sub_map.v or an always-fail map when adder binding is illegal.
    void emit(const VtrArchInfo &info, const ArchRulePolicy &policy, const std::string &outDir) const override {
        if (!info.adder.present) {
            log_warning("vtr_arch_rules: no adder model in arch; emitting "
                        "always-fail add_sub_map.v\n");
            writeFile(outDir + "/add_sub_map.v", alwaysFailAddSubMap(policy.archName, "arch has no adder model;"));
            return;
        }
        if (!info.adder.carryChain) {
            // non-carry wide-adder pb_types are not first-class, so emit soft-only maps
            // instead of an illegal carry-chain map against a non-carry model.
            log_warning("vtr_arch_rules: adder model '%s' is present but lacks carry-chain "
                        "ports (cin/cout/sumout); soft-only $add/$sub (always-fail "
                        "add_sub_map.v)\n",
                        policy.classic.adder.c_str());
            writeFile(outDir + "/add_sub_map.v",
                      alwaysFailAddSubMap(policy.archName, "adder model lacks carry-chain ports (cin/cout/sumout);"));
            return;
        }
        const std::map<std::string, std::string> scalars = {
            {"ARCH_NAME", policy.archName},
            {"HARD_ADDER_THRESHOLD", std::to_string(policy.hardAdderThreshold)},
            {"ADDER_MODEL", policy.classic.adder},
        };
        writeFile(outDir + "/add_sub_map.v",
                  substituteTemplate(loadTemplate(policy, "add_sub_map.v.tmpl"), scalars, {}));
    }

    // USE: contribute adder blackbox stub sized from scanned adder geometry.
    std::string hardblockStub(const VtrArchInfo &info, const ArchRulePolicy &policy) const override {
        if (!info.adder.present)
            return {};
        const std::map<std::string, std::string> scalars = {
            {"ADDER_WIDTH", std::to_string(std::max(1, info.adder.aWidth))},
            {"ADDER_MODEL", policy.classic.adder},
        };
        return finishStub(substituteTemplate(loadTemplate(policy, "adder_stub.v.tmpl"), scalars, {}));
    }
};

std::unique_ptr<ArchRuleGen> makeAdderRuleGen() { return std::unique_ptr<ArchRuleGen>(new AdderRuleGen()); }

